package render

import (
	"regexp"

	"github.com/microcosm-cc/bluemonday"
)

// policy is the allowlist over goldmark output. Raw HTML from the author
// never reaches it (goldmark renders with Unsafe disabled), so its job is
// the markdown-expressible residue: javascript:/vbscript:/data:text/html
// link and image destinations, event-handler attributes, and any tag goldmark
// would not emit itself — plus PERMITTING the desk embed elements our own
// renderers generate (video, same-origin PDF iframes, SVG charts, tables
// with classes, task-list checkboxes, footnotes, TOC nav).
var policy = func() *bluemonday.Policy {
	p := bluemonday.UGCPolicy()
	p.AllowDataURIImages()
	// Semantic classes ride on ordinary elements.
	p.AllowAttrs("class").OnElements(
		"div", "span", "pre", "code", "table", "thead", "tbody", "tfoot",
		"tr", "th", "td", "a", "img", "video", "source", "iframe",
		"figure", "figcaption", "nav", "ul", "ol", "li", "section",
		"sup", "p", "h1", "h2", "h3", "h4", "h5", "h6", "hr", "dl",
		"dt", "dd", "input", "svg",
	)
	// Heading ids (goldmark auto ids) so TOC anchors resolve.
	p.AllowAttrs("id").OnElements(
		"h1", "h2", "h3", "h4", "h5", "h6", "li", "sup", "section", "div", "a",
	)
	// Footnote backlinks and TOC anchors are same-document fragments.
	p.AllowAttrs("href").Matching(regexp.MustCompile(`^#`)).OnElements("a")
	// GFM task-list checkboxes.
	p.AllowElements("input")
	p.AllowAttrs("type", "checked", "disabled").OnElements("input")
	// Definition lists, figures, TOC nav.
	p.AllowElements("dl", "dt", "dd", "figure", "figcaption", "nav", "section")
	// Video embeds (client-side fetch of same-origin or opted-in remote).
	p.AllowElements("video", "source")
	p.AllowAttrs("src", "controls", "type", "title", "aria-label", "preload").OnElements("video", "source")
	// PDF embeds: same-origin viewer frame plus a download fallback.
	// Sources are generated by embeds.go (never author HTML), so the
	// element allowance cannot become an attacker iframe.
	p.AllowElements("iframe")
	p.AllowAttrs("src", "title", "loading", "width", "height").OnElements("iframe")
	// Chart SVGs: presentation attributes only, no <style> element and no
	// style attributes, so the strict view CSP keeps applying.
	p.AllowElements("svg", "g", "path", "rect", "circle", "line",
		"polyline", "polygon", "text", "title", "desc")
	p.AllowAttrs(
		"xmlns", "viewBox", "role", "aria-label",
		"x", "y", "cx", "cy", "r", "x1", "y1", "x2", "y2",
		"width", "height", "rx", "fill", "stroke", "stroke-width",
		"stroke-linejoin", "stroke-linecap", "opacity",
		"points", "text-anchor", "font-size", "font-family",
	).OnElements(
		"svg", "g", "path", "rect", "circle", "line",
		"polyline", "polygon", "text",
	)
	return p
}()

// sanitize runs rendered output through the allowlist.
func sanitize(in []byte) []byte {
	return policy.SanitizeBytes(in)
}
