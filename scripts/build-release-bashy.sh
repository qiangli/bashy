#!/usr/bin/env bash
# GoReleaser build tool: bind each Linux target to its own native runner gzip.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
case "${GOOS:-}/${GOARCH:-}" in
  linux/amd64|linux/arm64) ;;
  *) exec "$root/scripts/go-product.sh" "$@" ;;
esac
: "${BASHY_RUNNER_INPUT_DIR:?native runner inputs were not downloaded}"
: "${BASHY_RUNNER_WORK_ROOT:?isolated runner workspace root is required}"
target="${GOOS}-${GOARCH}"
gz="$BASHY_RUNNER_INPUT_DIR/runner-$target.gz"
manifest="$BASHY_RUNNER_INPUT_DIR/runner-$target.json"
work="$BASHY_RUNNER_WORK_ROOT/$target"
envfile="$BASHY_RUNNER_WORK_ROOT/$target.env"
mkdir -p "$BASHY_RUNNER_WORK_ROOT"
if [[ ! -s $envfile ]]; then
  tmp="$work.pending.$$"
  "$root/scripts/pinned-yoke-runner.sh" workspace "$GOOS" "$GOARCH" "$gz" "$manifest" "$tmp" > "$envfile.pending.$$"
  mv "$tmp" "$work"
  sed "s|$tmp|$work|g" "$envfile.pending.$$" > "$envfile"
  rm -f "$envfile.pending.$$"
fi
# Generated by pinned-yoke-runner.sh above.
set -a
# shellcheck disable=SC1090
source "$envfile"
set +a
exec "$root/scripts/go-product.sh" "$@"
