// GenerateOptions controls how cmdgen emits per-command main packages.
type GenerateOptions struct {
	GoVersion string            // defaults to "1.27.0"
	Toolchain string            // optional toolchain directive
	GoMod     GoModInfo         // optional host go.mod versions + replaces
	Replaces  []Replace         // additional replace directives
	LocalMods map[string]string // module path -> local directory path (emits go.work or path replaces)
}

// GeneratedFiles describes the generated files for one command.
type GeneratedFiles struct {
	Entry    Entry
	Dir      string
	MainPath string
	ModPath  string
	MainSrc  []byte
	ModSrc   []byte
	SpecHash string // SHA-256 of generated main.go + go.mod
}

type importSpec struct {
	alias string
	path  string
}

func parseImportSpec(spec string) (importSpec, error) {
	fields := strings.Fields(strings.TrimSpace(spec))
	switch len(fields) {
	case 1:
		return importSpec{path: strings.Trim(fields[0], `"`)}, nil
	case 2:
		return importSpec{alias: fields[0], path: strings.Trim(fields[1], `"`)}, nil
	default:
		return importSpec{}, fmt.Errorf("cmdgen: invalid import spec %q", spec)
	}
}

// GenerateMain renders deterministic, gofmt-formatted main.go source for entry.
func GenerateMain(entry Entry) ([]byte, error) {
	if err := entry.Validate(); err != nil {
		return nil, err
	}
	var src bytes.Buffer
	fmt.Fprintf(&src, "// Code generated by bashy cmdgen for %q (%s); DO NOT EDIT.\n\n", entry.Name, entry.Package)
	src.WriteString("package main\n\n")

	switch entry.Kind {
	case KindCobra:
		if err := renderCobraMain(&src, entry); err != nil {
			return nil, err
		}
	case KindTool:
		if err := renderToolMain(&src, entry); err != nil {
			return nil, err
		}
	case KindFunc:
		if err := renderFuncMain(&src, entry); err != nil {
			return nil, err
		}
	default:
		return nil, fmt.Errorf("cmdgen: unsupported kind %q", entry.Kind)
	}

	formatted, err := format.Source(src.Bytes())
	if err != nil {
		return nil, fmt.Errorf("cmdgen: gofmt %q: %w\nsource:\n%s", entry.Name, err, src.String())
	}
	return formatted, nil
}

func writeImports(w *bytes.Buffer, std, third []importSpec) {
	sort.Slice(std, func(i, j int) bool { return std[i].path < std[j].path })
	sort.Slice(third, func(i, j int) bool {
		if third[i].path != third[j].path {
			return third[i].path < third[j].path
		}
		return third[i].alias < third[j].alias
	})
	std = dedupImports(std)
	third = dedupImports(third)
	w.WriteString("import (\n")
	for _, imp := range std {
		writeImportLine(w, imp)
	}
	if len(std) > 0 && len(third) > 0 {
		w.WriteByte('\n')
	}
	for _, imp := range third {
		writeImportLine(w, imp)
	}
	w.WriteString(")\n\n")
}

func dedupImports(in []importSpec) []importSpec {
	var out []importSpec
	for _, imp := range in {
		if len(out) > 0 && out[len(out)-1] == imp {
			continue
		}
		out = append(out, imp)
	}
	return out
}

func writeImportLine(w *bytes.Buffer, imp importSpec) {
	if imp.alias != "" {
		fmt.Fprintf(w, "\t%s %q\n", imp.alias, imp.path)
	} else {
		fmt.Fprintf(w, "\t%q\n", imp.path)
	}
}

func appendExtraImports(std, third *[]importSpec, extras []string) error {
	for _, raw := range extras {
		imp, err := parseImportSpec(raw)
		if err != nil {
			return err
		}
		if isStdlibImport(imp.path) {
			*std = append(*std, imp)
		} else {
			*third = append(*third, imp)
		}
	}
	return nil
}

func isStdlibImport(p string) bool {
	first := p
	if i := strings.IndexByte(p, '/'); i >= 0 {
		first = p[:i]
	}
	return !strings.ContainsRune(first, '.')
}

func renderCobraMain(w *bytes.Buffer, e Entry) error {
	std := []importSpec{{path: "os"}}
	if e.PrintError() {
		std = append(std, importSpec{path: "fmt"})
	}
	third := []importSpec{{alias: "cmdpkg", path: e.Package}}
	if err := appendExtraImports(&std, &third, e.ExtraImports); err != nil {
		return err
	}
	writeImports(w, std, third)

	w.WriteString("func main() {\n")
	for _, stmt := range e.Setup {
		fmt.Fprintf(w, "\t%s\n", stmt)
	}
	ctor := strings.TrimSpace(e.Constructor)
	if !strings.Contains(ctor, "(") {
		ctor += "()"
	}
	if !strings.Contains(ctor, ".") {
		ctor = "cmdpkg." + ctor
	}
	fmt.Fprintf(w, "\tcmd := %s\n", ctor)
	if e.Use != "" {
		fmt.Fprintf(w, "\tcmd.Use = %q\n", e.Use)
	}
	if e.DisableCompletion() {
		w.WriteString("\tcmd.CompletionOptions.DisableDefaultCmd = true\n")
	}
	for _, stmt := range e.PostConstruct {
		fmt.Fprintf(w, "\t%s\n", stmt)
	}
	if len(e.PrependArgs) > 0 {
		fmt.Fprintf(w, "\targs := append(%#v, os.Args[1:]...)\n", e.PrependArgs)
		w.WriteString("\tcmd.SetArgs(args)\n")
	} else {
		w.WriteString("\tcmd.SetArgs(os.Args[1:])\n")
	}
	w.WriteString("\tif err := cmd.Execute(); err != nil {\n")
	if e.PrintError() {
		fmt.Fprintf(w, "\t\tfmt.Fprintf(os.Stderr, \"bashy %s: %%v\\n\", err)\n", e.Name)
	}
	if ef := strings.TrimSpace(e.ExitFunc); ef != "" {
		if !strings.Contains(ef, ".") {
			ef = "cmdpkg." + ef
		}
		fmt.Fprintf(w, "\t\tos.Exit(%s(err))\n", ef)
	} else {
		w.WriteString("\t\tos.Exit(1)\n")
	}
	w.WriteString("\t}\n")
	w.WriteString("}\n")
	return nil
}

func renderToolMain(w *bytes.Buffer, e Entry) error {
	std := []importSpec{
		{path: "context"},
		{path: "fmt"},
		{path: "os"},
	}
	third := []importSpec{
		{path: "github.com/qiangli/coreutils/tool"},
		{alias: "_", path: e.Package},
	}
	if err := appendExtraImports(&std, &third, e.ExtraImports); err != nil {
		return err
	}
	writeImports(w, std, third)

	toolName := e.ToolName
	if toolName == "" {
		toolName = e.Name
	}

	w.WriteString("func main() {\n")
	for _, stmt := range e.Setup {
		fmt.Fprintf(w, "\t%s\n", stmt)
	}
	fmt.Fprintf(w, "\tt := tool.Lookup(%q)\n", toolName)
	w.WriteString("\tif t == nil {\n")
	fmt.Fprintf(w, "\t\tfmt.Fprintf(os.Stderr, \"bashy: %s: No such command\\n\")\n", toolName)
	w.WriteString("\t\tos.Exit(127)\n")
	w.WriteString("\t}\n")
	w.WriteString("\tdir, err := os.Getwd()\n")
	w.WriteString("\tif err != nil {\n")
	fmt.Fprintf(w, "\t\tfmt.Fprintf(os.Stderr, \"bashy: %s: %%v\\n\", err)\n", toolName)
	w.WriteString("\t\tos.Exit(1)\n")
	w.WriteString("\t}\n")
	w.WriteString("\trc := &tool.RunContext{\n")
	w.WriteString("\t\tCtx: context.Background(),\n")
	w.WriteString("\t\tDir: dir,\n")
	w.WriteString("\t\tEnv: os.Environ(),\n")
	w.WriteString("\t\tFS:  tool.NewLocalFS(),\n")
	w.WriteString("\t\tStdio: tool.Stdio{\n")
	w.WriteString("\t\t\tIn:  os.Stdin,\n")
	w.WriteString("\t\t\tOut: os.Stdout,\n")
	w.WriteString("\t\t\tErr: os.Stderr,\n")
	w.WriteString("\t\t},\n")
	w.WriteString("\t}\n")
	if len(e.PrependArgs) > 0 {
		fmt.Fprintf(w, "\targs := append(%#v, os.Args[1:]...)\n", e.PrependArgs)
		w.WriteString("\tos.Exit(t.Run(rc, args))\n")
	} else {
		w.WriteString("\tos.Exit(t.Run(rc, os.Args[1:]))\n")
	}
	w.WriteString("}\n")
	return nil
}

func renderFuncMain(w *bytes.Buffer, e Entry) error {
	sig := e.ArgsSignature
	if sig == "" {
		sig = SigArgs
	}
	std := []importSpec{{path: "os"}}
	if sig == SigCtxArgs {
		std = append(std, importSpec{path: "context"})
	}
	third := []importSpec{{alias: "cmdpkg", path: e.Package}}
	if err := appendExtraImports(&std, &third, e.ExtraImports); err != nil {
		return err
	}
	writeImports(w, std, third)

	fn := strings.TrimSpace(e.Constructor)
	if !strings.Contains(fn, ".") {
		fn = "cmdpkg." + fn
	}

	w.WriteString("func main() {\n")
	for _, stmt := range e.Setup {
		fmt.Fprintf(w, "\t%s\n", stmt)
	}
	argsExpr := "os.Args[1:]"
	if len(e.PrependArgs) > 0 {
		fmt.Fprintf(w, "\targs := append(%#v, os.Args[1:]...)\n", e.PrependArgs)
		argsExpr = "args"
	}
	switch sig {
	case SigArgs:
		fmt.Fprintf(w, "\tos.Exit(%s(%s))\n", fn, argsExpr)
	case SigCtxArgs:
		fmt.Fprintf(w, "\tos.Exit(%s(context.Background(), %s))\n", fn, argsExpr)
	case SigArgsOutErr:
		fmt.Fprintf(w, "\tos.Exit(%s(%s, os.Stdout, os.Stderr))\n", fn, argsExpr)
	case SigArgsStdio:
		fmt.Fprintf(w, "\tos.Exit(%s(%s, os.Stdin, os.Stdout, os.Stderr))\n", fn, argsExpr)
	}
	w.WriteString("}\n")
	return nil
}

// GenerateGoMod renders a deterministic go.mod for a generated command main.
func GenerateGoMod(entry Entry, opts GenerateOptions) ([]byte, error) {
	entry = entry.ResolveVersion(opts.GoMod)
	if err := entry.Validate(); err != nil {
		return nil, err
	}
	goVer := opts.GoVersion
	if goVer == "" {
		goVer = opts.GoMod.GoVersion
	}
	if goVer == "" {
		goVer = "1.27.0"
	}
	version := entry.Version
	if version == "" {
		version = "v0.0.0"
	}

	reqs := map[string]string{
		entry.Module: version,
	}
	if entry.Kind == KindTool {
		if _, exists := reqs["github.com/qiangli/coreutils"]; !exists {
			if v, ok := opts.GoMod.Requires["github.com/qiangli/coreutils"]; ok {
				reqs["github.com/qiangli/coreutils"] = v
			} else {
				reqs["github.com/qiangli/coreutils"] = "v0.0.0"
			}
		}
	}
	for _, r := range entry.ExtraRequires {
		v := r.Version
		if v == "" {
			if pinned, ok := opts.GoMod.Requires[r.Module]; ok {
				v = pinned
			} else {
				v = "v0.0.0"
			}
		}
		reqs[r.Module] = v
	}

	var modNames []string
	for m := range reqs {
		modNames = append(modNames, m)
	}
	sort.Strings(modNames)

	var b bytes.Buffer
	fmt.Fprintf(&b, "module bashy-cmd/%s\n\n", entry.Name)
	fmt.Fprintf(&b, "go %s\n", goVer)
	if tc := opts.Toolchain; tc != "" {
		fmt.Fprintf(&b, "\ntoolchain %s\n", tc)
	} else if opts.GoMod.Toolchain != "" {
		fmt.Fprintf(&b, "\ntoolchain %s\n", opts.GoMod.Toolchain)
	}
	b.WriteString("\nrequire (\n")
	for _, m := range modNames {
		fmt.Fprintf(&b, "\t%s %s\n", m, reqs[m])
	}
	b.WriteString(")\n")

	var replaces []Replace
	replaces = append(replaces, opts.GoMod.Replaces...)
	replaces = append(replaces, opts.Replaces...)
	if len(replaces) > 0 {
		b.WriteByte('\n')
		seen := map[string]bool{}
		for _, r := range replaces {
			key := r.OldPath + "@" + r.OldVersion
			if seen[key] {
				continue
			}
			seen[key] = true
			if r.OldVersion != "" {
				if r.NewVersion != "" {
					fmt.Fprintf(&b, "replace %s %s => %s %s\n", r.OldPath, r.OldVersion, r.NewPath, r.NewVersion)
				} else {
					fmt.Fprintf(&b, "replace %s %s => %s\n", r.OldPath, r.OldVersion, r.NewPath)
				}
			} else if r.NewVersion != "" {
				fmt.Fprintf(&b, "replace %s => %s %s\n", r.OldPath, r.NewPath, r.NewVersion)
			} else {
				fmt.Fprintf(&b, "replace %s => %s\n", r.OldPath, r.NewPath)
			}
		}
	}
	return b.Bytes(), nil
}

// GenerateDir writes main.go and go.mod for entry into outDir.
func GenerateDir(entry Entry, outDir string, opts GenerateOptions) (GeneratedFiles, error) {
	mainSrc, err := GenerateMain(entry)
	if err != nil {
		return GeneratedFiles{}, err
	}
	modSrc, err := GenerateGoMod(entry, opts)
	if err != nil {
		return GeneratedFiles{}, err
	}
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return GeneratedFiles{}, err
	}
	mainPath := filepath.Join(outDir, "main.go")
	modPath := filepath.Join(outDir, "go.mod")
	if err := os.WriteFile(mainPath, mainSrc, 0o644); err != nil {
		return GeneratedFiles{}, err
	}
	if err := os.WriteFile(modPath, modSrc, 0o644); err != nil {
		return GeneratedFiles{}, err
	}
	h := sha256.New()
	h.Write([]byte("main.go\x00"))
	h.Write(mainSrc)
	h.Write([]byte("\x00go.mod\x00"))
	h.Write(modSrc)
	return GeneratedFiles{
		Entry:    entry.ResolveVersion(opts.GoMod),
		Dir:      outDir,
		MainPath: mainPath,
		ModPath:  modPath,
		MainSrc:  mainSrc,
		ModSrc:   modSrc,
		SpecHash: hex.EncodeToString(h.Sum(nil)),
	}, nil
}

// GenerateAll emits one subdirectory (<outRoot>/<name>/{main.go,go.mod}) per
// catalog entry.
func GenerateAll(entries []Entry, outRoot string, opts GenerateOptions) ([]GeneratedFiles, error) {
	out := make([]GeneratedFiles, 0, len(entries))
	for _, e := range entries {
		dir := filepath.Join(outRoot, e.Name)
		gf, err := GenerateDir(e, dir, opts)
		if err != nil {
			return nil, err
		}
		out = append(out, gf)
	}
	return out, nil
}

// PackageRelDir returns the slash-separated directory of entry.Package relative
// to entry.Module (or "." when package == module).
func (e Entry) PackageRelDir() (string, bool) {
	if e.Package == e.Module {
		return ".", true
	}
	prefix := e.Module + "/"
	if !strings.HasPrefix(e.Package, prefix) {
		return "", false
	}
	rel := path.Clean(strings.TrimPrefix(e.Package, prefix))
	if rel == ".." || strings.HasPrefix(rel, "../") {
		return "", false
	}
	return rel, true
}
